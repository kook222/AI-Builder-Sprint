// 위험 문장 추출 입력 만들기
export function buildPageUser(url, query, labels, text) {
  const head = [
    `페이지 주소: ${url}`,
    query ? `사용자가 검색했던 말: ${query}` : null,
    labels?.length ? `검색 목록에서 이미 붙은 의심: ${labels.join(', ')}` : null,
  ]
    .filter(Boolean)
    .join('\n');

  return `${head}\n\n본문:\n${text.slice(0, 12000)}`;
}
